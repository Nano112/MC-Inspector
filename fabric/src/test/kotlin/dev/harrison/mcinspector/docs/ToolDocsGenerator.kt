package dev.harrison.mcinspector.docs

import dev.harrison.mcinspector.config.InspectorConfig
import dev.harrison.mcinspector.log.LogRingBuffer
import dev.harrison.mcinspector.mcp.ToolRegistry
import dev.harrison.mcinspector.tools.Tools
import java.nio.file.Files
import java.nio.file.Path

/** `./gradlew :fabric:<ver>:generateToolDocs` — writes docs/mcp-tools.md from the registry (no game needed). */
fun main(args: Array<String>) {
    val out = Path.of(args.firstOrNull() ?: "docs").resolve("mcp-tools.md")
    val reg = ToolRegistry().also { Tools.registerAll(it, InspectorConfig(), LogRingBuffer(10)) }
    val sb = StringBuilder()
    sb.append("# MC-Inspector MCP tools\n\nGenerated by `./gradlew :fabric:1.21.11:generateToolDocs` (${reg.size} tools). Connect with `.mcp.json` (in this repo) or\n`claude mcp add --transport http mcinspector http://127.0.0.1:38271/mcp`.\n\n")
    sb.append("""## Coordinate spaces

- **Image pixels** — what `screenshot` returns. Multiply by its `mouseScale` to get mouse coordinates.
- **Mouse coordinates** — logical window units used by `mouse_move`, `mouse_click`, `mouse_scroll` (`mouseWidth`/`mouseHeight` in `get_state`).
- **GUI coordinates** — what `list_widgets` reports; multiply by its `guiToMouse` to get mouse coordinates. Prefer `click_widget`.

## Typical loops

- One call for a whole flow: `run_sequence` with `waitFor` (see its description).
- Menus: `get_screen` → `list_widgets` → `click_widget {text}` / `set_text_field` / `type_text` → `screenshot`.
- In-world: `hold_key w` → `wait_ticks 40` → `release_key w`; `mouse_move {relative:true}` to look; `press_key e` for inventory; `run_command`.
- panel-lib overlay: `press_key k` toggles it (`i` = MCP Host panel, `o` = Packets panel); `get_state.panellib` lists open panels; `mouse_click` on ImGui widgets (the tool settles 2 ticks after moving so ImGui claims the click).
- Packets: `packets_stats` to see what is flowing, `packets_capture {exclude:["keep_alive|set_time"]}` to cut noise, `packets_list {type:"chat", since:<lastId>}` to poll, `packets_get {id}` for decoded fields.
- Debugging: `read_logs {filter, level}` after any step; `get_state` to confirm screen / position.

""")
    for (t in reg.all()) {
        sb.append("### ${t.name}\n\n${t.description}\n\n")
        val props = t.inputSchema.getAsJsonObject("properties")
        val required = t.inputSchema.getAsJsonArray("required")?.map { it.asString }?.toSet() ?: emptySet()
        if (props == null || props.size() == 0) { sb.append("_No arguments._\n\n"); continue }
        sb.append("| arg | type | description |\n|---|---|---|\n")
        for ((k, v) in props.entrySet()) {
            val o = v.asJsonObject
            val type = o.get("type").asString + (o.getAsJsonArray("enum")?.let { " (" + it.joinToString(", ") { e -> e.asString } + ")" } ?: "")
            sb.append("| `$k`${if (k in required) " (required)" else ""} | $type | ${o.get("description").asString.replace("|", "\\|").replace("\n", " ")} |\n")
        }
        sb.append("\n")
    }
    Files.createDirectories(out.parent)
    Files.writeString(out, sb.toString())
    println("wrote $out (${reg.size} tools)")
}
